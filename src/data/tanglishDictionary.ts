/**
 * Returns the Tanglish transliteration if available.
 * E.g. "Tomato" -> "Thakkali", "Rice" -> "Arisi"
 */
export function getTanglishName(englishName: string): string | null {
  if (!englishName) return null;
  const clean = englishName.trim().toLowerCase();
  
  if (TANGLISH_DICTIONARY[clean]) {
    return TANGLISH_DICTIONARY[clean];
  }

  // Check partial key matches
  for (const [key, val] of Object.entries(TANGLISH_DICTIONARY)) {
    if (clean.includes(key) || key.includes(clean)) {
      return val;
    }
  }

  return null;
}

/**
 * Formats a display name based on Tanglish mode.
 * When isTanglish is true: "Tomato (Thakkali)"
 * When false: "Tomato"
 */
export function formatIngredientName(name: string, isTanglish: boolean): string {
  if (!isTanglish) return name;
  const tanglish = getTanglishName(name);
  if (tanglish) {
    // If the name already includes the Tanglish word, avoid duplication
    if (name.toLowerCase().includes(tanglish.toLowerCase())) {
      return name;
    }
    return `${name} (${tanglish})`;
  }
  return name;
}
